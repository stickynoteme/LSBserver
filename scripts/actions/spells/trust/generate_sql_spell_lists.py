    print(f"  Total spell lists: {len(list_id_map)}")
    print(f"  ID range: 566 to {next_id - 1}")
    print(f"  File size: {len(sql_content):,} bytes")
    print(f"  Spells with extracted level data: {stats['with_levels']:,}")
    print(f"  Spells using defaults: {stats['without_levels']:,}")

    # Also create a mapping file for reference
