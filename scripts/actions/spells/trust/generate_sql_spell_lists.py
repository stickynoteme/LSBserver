#!/usr/bin/env python3
"""
Generate SQL INSERT statements for spell lists to be added to mob_spell_lists.sql

This script creates SQL entries for all single-job and job combination spell lists,
allowing the server to recognize and use these spell lists.
"""

import re
from pathlib import Path
from itertools import combinations
from collections import defaultdict

# Magic jobs
